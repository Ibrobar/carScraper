/** Great-circle distance in miles. */
export function haversineMiles([lat1, lon1], [lat2, lon2]) {
  const toRad = (d) => (d * Math.PI) / 180;
  const dLat = toRad(lat2 - lat1);
  const dLon = toRad(lon2 - lon1);
  const a = Math.sin(dLat / 2) ** 2
    + Math.cos(toRad(lat1)) * Math.cos(toRad(lat2)) * Math.sin(dLon / 2) ** 2;
  return 2 * R_MILES * Math.asin(Math.min(1, Math.sqrt(a)));
}

/**
 * "Fort Worth, TX" -> "fort worth,tx". Facebook also writes a bare city with no
 * state ("Houston"), so the state is optional and inferred as TX when missing —
 * these searches are Texas-centred and a bare name is nearly always in-state.
 */
export function normalizeLocation(text) {
  if (!text) return null;
  const clean = String(text)
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[^a-z,\s]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
  if (!clean) return null;

  const [cityPart, statePart] = clean.split(',').map((s) => s.trim());
  if (!cityPart) return null;
  const state = (statePart || 'tx').slice(0, 2);
  return `${cityPart},${state}`;
}

/**
 * Bare city name -> the one state it appears in, for names that are
 * unambiguous. Facebook writes "Oklahoma City" and "Fort Smith" with no state,
 * and assuming Texas would put them 200 miles from where they really are. Names
 * that exist in more than one state (Cleveland, Paris, Converse, Chandler…) are
 * excluded on purpose — for those the Texas assumption is the better guess.
 */
const UNIQUE_CITY_STATE = (() => {
  const seen = new Map();
  for (const key of Object.keys(CITY_COORDS)) {
    const [city, state] = key.split(',');
    if (seen.has(city)) seen.set(city, null);
    else seen.set(city, state);
  }
  return seen;
})();

export function coordsFor(locationText) {
  const key = normalizeLocation(locationText);
  if (!key) return null;
  const direct = CITY_COORDS[key];
  if (direct) return direct;

  // No explicit state and no Texas match: fall back to the single state this
  // city name exists in, when there is exactly one.
  if (/,\s*[a-z]{2}\s*$/i.test(String(locationText).trim())) return null;
  const city = key.split(',')[0];
  const state = UNIQUE_CITY_STATE.get(city);
  return state ? (CITY_COORDS[`${city},${state}`] ?? null) : null;
}

/**
 * Miles from a metro centre, or null when the city isn't in the table.
 * Null means "don't know" and callers must treat it as keep, not reject.
 */
export function milesFromCenter(locationText, center) {
  const coords = coordsFor(locationText);
  if (!coords || !center) return null;
  return haversineMiles(coords, center);
}
