// 91 Austin, 297 from Oklahoma and 76 from Arkansas — against 83 from Dallas
// itself. Facebook ignores the URL radius and serves the account's saved
// Marketplace location instead (Irving, "within 250 mi").
//
// `tools/probe_search.js` confirmed the search payload carries
// `reverse_geocode: {city, state}` per listing but NO per-listing coordinates —
// the only latitude on the page is the search centre. So distance has to come
// from a city lookup on our side, and the table has to be big enough that
// "unknown" is rare. The first version had 118 cities and missed 497 towns
// across 899 listings, which meant the filter mostly wasn't running.
//
// Coordinates are town centres to within a couple of miles. That's plenty for a
// 150-mile threshold: only a handful of towns sit near the line, and everything
// this filter actually exists to cut (Austin, San Antonio, Houston, Oklahoma
// City, Tulsa, Fort Smith, Shreveport) is 50+ miles clear of it.
//
// Unknown cities are KEPT, not rejected — same rule as the make blocklist. A
// small town we don't have coordinates for is more likely to be a nearby suburb
// than a distant one, and dropping what we can't identify is how the origin
// filter once ate 142 of 219 listings.

